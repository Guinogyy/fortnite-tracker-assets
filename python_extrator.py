import requests
from bs4 import BeautifulSoup

def compilar_documentacao(lista_urls, nome_arquivo_saida):
    print(f"Iniciando a compilação de {len(lista_urls)} páginas...\n")
    headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'}
    
    # Abre o arquivo em modo de escrita ('w') uma única vez
    with open(nome_arquivo_saida, 'w', encoding='utf-8') as arquivo:
        for url in lista_urls:
            print(f"Extraindo: {url}")
            try:
                resposta = requests.get(url, headers=headers)
                resposta.raise_for_status()
                sopa = BeautifulSoup(resposta.text, 'html.parser')
                
                area_principal = sopa.find('main') or sopa.find('article') or sopa.body
                
                if area_principal:
                    texto_limpo = area_principal.get_text(separator='\n', strip=True)
                    
                    # Cria uma divisória visual no arquivo de texto para separar os tópicos
                    arquivo.write(f"\n{'='*60}\n")
                    arquivo.write(f"TÓPICO: {url}\n")
                    arquivo.write(f"{'='*60}\n\n")
                    arquivo.write(texto_limpo)
                    arquivo.write("\n\n")
                else:
                    print(f"⚠️ Aviso: Corpo principal não encontrado em {url}")
                    
            except Exception as erro:
                print(f"❌ Falha ao acessar {url}: {erro}")
    
    print(f"\n✅ Compilação concluída! Tudo foi unificado no arquivo: {nome_arquivo_saida}")

